import 'dart:io';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';
import 'package:thermion_dart/src/hooks/material_tools.dart';
import 'package:thermion_dart/src/hooks/material_publication.dart';
import 'material_tools_test.dart' show FakeTools;

void main() {
  late Directory root;
  setUp(() => root = Directory.systemTemp.createTempSync('material-publication-'));
  tearDown(() => root.deleteSync(recursive: true));
  File write(String name, String text) {
    final file = File(p.join(root.path, name));
    file.parent.createSync(recursive: true);
    return file..writeAsStringSync(text);
  }

  Future<UserMaterialsResult> compile(
    FakeTools tools, {
    ToolProcess? runner,
    void Function(String)? log,
    bool resgen = false,
  }) => compileUserMaterials(
    appRoot: root,
    config: parseMaterialCompilationConfig({
      'inputs': ['materials'],
      'output': 'out',
      'resgen': resgen,
    })!,
    filamentVersion: 'v1.77.2',
    packageVersion: 'test',
    hostOS: 'macos',
    hostArch: 'arm64',
    toolsCacheRoot: p.join(root.path, 'tools'),
    download: tools.downloader(),
    runProcess: runner ?? tools.run,
    onLog: log,
  );

  test('tracks nested includes and ignores commented include directives', () async {
    write('materials/skin.mat', 'fragment {\n#include "common.glsl"\n}');
    write(
      'materials/common.glsl',
      '#include "nested/color.glsl"\n// #include "not-a-file"\n/* #include "also-not-a-file" */',
    );
    final included = write('materials/nested/color.glsl', 'color one');
    write('materials/eye.mat', 'unrelated');
    final tools = FakeTools();
    final first = await compile(tools);
    expect(first.dependencies, containsAll([included.uri, Directory(p.join(root.path, 'materials/nested')).uri]));
    included.writeAsStringSync('color two');
    final changed = await compile(tools);
    expect(changed.compiled, 1);
    expect(changed.skipped, 1);
  });

  test('missing and cyclic includes fail without publishing', () async {
    final source = write('materials/skin.mat', '#include "missing.glsl"');
    final tools = FakeTools();
    await expectLater(
      compile(tools),
      throwsA(isA<MaterialGenerationError>().having((e) => e.message, 'missing include', contains('missing.glsl'))),
    );
    source.writeAsStringSync('#include "loop.glsl"');
    write('materials/loop.glsl', '#include "skin.mat"');
    await expectLater(
      compile(tools),
      throwsA(isA<MaterialGenerationError>().having((e) => e.message, 'cycle', contains('cycle'))),
    );
    expect(tools.matcCompiles, isEmpty);
  });

  test('moving a source preserves its replacement output and drops its old manifest key', () async {
    final source = write('materials/old/skin.mat', 'skin');
    final tools = FakeTools();
    await compile(tools);
    Directory(p.join(root.path, 'materials/new')).createSync();
    source.renameSync(p.join(root.path, 'materials/new/skin.mat'));
    final result = await compile(tools);
    expect(result.compiled, 1);
    expect(File(p.join(root.path, 'out/skin.filamat')).existsSync(), isTrue);
    final manifest = readMaterialsManifest(File(p.join(root.path, 'out', materialManifestName)))!;
    expect(manifest.outputs.keys, ['materials/new/skin.mat']);
    expect((await compile(tools)).compiled, 0);
  });

  test('changed generated bytes are rebuilt and generated files are hook dependencies', () async {
    write('materials/skin.mat', 'skin');
    final tools = FakeTools();
    final result = await compile(tools);
    final output = File(p.join(root.path, 'out/skin.filamat'));
    expect(result.dependencies, containsAll([output.uri, File(p.join(root.path, 'out', materialManifestName)).uri]));
    output.writeAsStringSync('corrupt');
    expect((await compile(tools)).compiled, 1);
    output.deleteSync();
    expect((await compile(tools)).compiled, 1);
  });

  test('a later compile failure publishes nothing even after sources are reverted', () async {
    final a = write('materials/a.mat', 'A original');
    final b = write('materials/b.mat', 'B original');
    final tools = FakeTools();
    var failB = false;
    Future<ToolRunResult> runner(String executable, List<String> args) async {
      if (failB && p.basename(args.last) == 'b.mat') return (exitCode: 1, stdout: '', stderr: 'B failed');
      final result = await tools.run(executable, args);
      if (executable.endsWith('matc') && p.basename(args.last) != 'smoke.mat' && result.exitCode == 0) {
        File(args[args.indexOf('-o') + 1]).writeAsStringSync(File(args.last).readAsStringSync());
      }
      return result;
    }

    await compile(tools, runner: runner);
    a.writeAsStringSync('A abandoned');
    b.writeAsStringSync('B abandoned');
    failB = true;
    await expectLater(compile(tools, runner: runner), throwsA(isA<MaterialGenerationError>()));
    expect(File(p.join(root.path, 'out/a.filamat')).readAsStringSync(), 'A original');
    a.writeAsStringSync('A original');
    b.writeAsStringSync('B original');
    failB = false;
    expect((await compile(tools, runner: runner)).compiled, 0);
    expect(File(p.join(root.path, 'out/a.filamat')).readAsStringSync(), 'A original');
  });

  test('publication failure restores all old bytes and the old manifest', () async {
    final source = write('materials/skin.mat', 'original');
    final tools = FakeTools();
    await compile(tools, resgen: true);
    final output = Directory(p.join(root.path, 'out'));
    final files = output.listSync().whereType<File>().where((f) => !p.basename(f.path).endsWith('.lock')).toList();
    final before = {for (final file in files) p.basename(file.path): file.readAsBytesSync()};
    source.writeAsStringSync('changed');
    await expectLater(
      compile(
        tools,
        resgen: true,
        log: (message) {
          if (message.contains('published ')) throw StateError('injected publication failure');
        },
      ),
      throwsStateError,
    );
    for (final entry in before.entries) expect(File(p.join(output.path, entry.key)).readAsBytesSync(), entry.value);
    expect(File(p.join(output.path, materialJournalName)).existsSync(), isFalse);
  });

  test('concurrent helper calls serialize one output generation', () async {
    write('materials/skin.mat', 'skin');
    final tools = FakeTools();
    final results = await Future.wait([compile(tools), compile(tools)]);
    expect(results.map((r) => r.compiled).toList()..sort(), [0, 1]);
  });

  test(
    'process interruption is recovered before a reverted source can be skipped',
    () async {
      final a = write('materials/a.mat', 'A original');
      final b = write('materials/b.mat', 'B original');
      Future<ProcessResult> worker([String? mode]) => Process.run(Platform.resolvedExecutable, [
        'run',
        'test/fixtures/material_transaction_worker.dart',
        root.path,
        if (mode != null) mode,
      ]);
      final initial = await worker();
      expect(initial.exitCode, 0, reason: '${initial.stdout}\n${initial.stderr}');
      a.writeAsStringSync('A abandoned');
      b.writeAsStringSync('B abandoned');
      final interrupted = await worker('interrupt');
      expect(interrupted.exitCode, 75, reason: '${interrupted.stdout}\n${interrupted.stderr}');
      expect(File(p.join(root.path, 'out', materialJournalName)).existsSync(), isTrue);
      a.writeAsStringSync('A original');
      b.writeAsStringSync('B original');
      final recovered = await worker();
      expect(recovered.exitCode, 0, reason: '${recovered.stdout}\n${recovered.stderr}');
      expect(recovered.stdout, contains('compiled=0'));
      expect(File(p.join(root.path, 'out/a.filamat')).readAsStringSync(), 'A original');
      expect(File(p.join(root.path, 'out/b.filamat')).readAsStringSync(), 'B original');
      expect(File(p.join(root.path, 'out', materialJournalName)).existsSync(), isFalse);
    },
    timeout: const Timeout(Duration(minutes: 2)),
  );

  test('native linking is explicitly unavailable in the core compilation PR', () {
    expect(
      () => parseMaterialCompilationConfig({
        'inputs': ['materials'],
        'output': 'out',
        'link_generated': true,
      }),
      throwsA(isA<MaterialToolsError>()),
    );
  });
}
